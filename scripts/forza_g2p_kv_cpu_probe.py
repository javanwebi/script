def session(path):
    opts = ort.SessionOptions()
    opts.intra_op_num_threads = 1
    opts.inter_op_num_threads = 1
    opts.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
    opts.enable_cpu_mem_arena = False
    opts.enable_mem_pattern = False
    return ort.InferenceSession(str(path), opts, providers=["CPUExecutionProvider"])


def manifest(sess):
    return {
        "inputs": [{"name": x.name, "shape": x.shape, "type": x.type}
                   for x in sess.get_inputs()],
        "outputs": [{"name": x.name, "shape": x.shape, "type": x.type}
                    for x in sess.get_outputs()],
    }


class IncompatibleKV(RuntimeError):
    pass


def role(name):
    """Conservative normalization of graph ABI names, not weights/meaning."""
    return name.lower().replace("-", "_").replace(".", "_")


def numeric_shape(spec, length=0):
    dims = []
    for i, v in enumerate(spec.shape):
        if isinstance(v, int) and v >= 0:
            dims.append(v)
        elif i == 0:
            dims.append(1)
        elif i == 2:
            dims.append(length)
        else:
            raise IncompatibleKV("unknown_dynamic_cache_dimension: " + spec.name +
                                 " shape=" + str(spec.shape))
    return dims


class CachedG2P(OnnxG2P):
    """Only the decoder loop is changed; inherit identical normalization."""
    def __init__(self, candidate_dir):
        # Avoid double-loading the legacy model to respect the VPS 2 GiB limit.
        self.s_enc = session(Path(candidate_dir) / "g2p_encoder_kv.onnx")
        self.s_dec = session(Path(candidate_dir) / "g2p_decoder_kv.onnx")
        self.max_len = 512
        self.enc_outputs = {x.name: i for i, x in enumerate(self.s_enc.get_outputs())}
        self.dec_inputs = self.s_dec.get_inputs()
        self.dec_outputs = self.s_dec.get_outputs()
        self._check_abi()

    def _check_abi(self):
        ins = [role(i.name) for i in self.dec_inputs]
        outs = [role(i.name) for i in self.dec_outputs]
        if not any(n in ("token", "decoder_input_ids", "input_ids") for n in ins):
            raise IncompatibleKV("missing_single_token_input: " + str(ins))
        if not any("logits" in n for n in outs):
            raise IncompatibleKV("missing_logits_output: " + str(outs))
        if not any("past" in n for n in ins):
            raise IncompatibleKV("missing_past_kv_inputs: " + str(ins))
        if not any("present" in n for n in outs):
            raise IncompatibleKV("missing_present_kv_outputs: " + str(outs))

    def _decode_greedy(self, text):
        ids = encode(text)
        if not ids:
            return ""
        values = self.s_enc.run(None, {"input_ids": np.asarray([ids], dtype=np.int64)})
        available = dict(zip((x.name for x in self.s_enc.get_outputs()), values))
        cached = {}
        result = []
        token = np.asarray([[PAD]], dtype=np.int64)

        def match_encoder_input(name):
            # Cross-attention K/V are pregenerated by the *same candidate*
            # encoder. Only accept an exact tensor name after normalization;
            # do not guess cross-attention layer order.
            matches = [v for k, v in available.items() if role(k) == role(name)]
            if len(matches) == 1:
                return matches[0]
            if role(name) in ("encoder_hidden", "hidden"):
                h = [v for k, v in available.items() if "hidden" in role(k)]
                if len(h) == 1:
                    return h[0]
            raise IncompatibleKV("no_exact_encoder_cross_kv_match: " + name)

        for _ in range(self.max_len):
            feed = {}
            for item in self.dec_inputs:
                n = role(item.name)
                if n in ("token", "decoder_input_ids", "input_ids"):
                    feed[item.name] = token
                elif n.startswith("past_"):
                    if item.name not in cached:
                        cached[item.name] = np.zeros(
                            numeric_shape(item), dtype=np.float32)
                    feed[item.name] = cached[item.name]
                else:
                    feed[item.name] = match_encoder_input(item.name)
            outputs = self.s_dec.run(None, feed)
            done = dict(zip((x.name for x in self.dec_outputs), outputs))
            logits = [v for k, v in done.items() if "logits" in role(k)]
            if len(logits) != 1:
                raise IncompatibleKV("logits_count_not_one")
            token_id = int(np.argmax(logits[0].reshape(-1)))
            if token_id == EOS:
                break
            result.append(token_id)
            token = np.asarray([[token_id]], dtype=np.int64)
            next_cache = {}
            for key in (i.name for i in self.dec_inputs if role(i.name).startswith("past_")):
                suffix = role(key)[len("past_"):]
                present = [v for k, v in done.items() if role(k) == "present_" + suffix]
                if len(present) != 1:
                    raise IncompatibleKV("missing_matching_present_for: " + key)
                next_cache[key] = present[0]
            cached = next_cache
        else:
            raise IncompatibleKV("kv_decoder_no_eos_after_512")
        return decode(result)


def timed_phonemes(engine, phrases):
    out = []
    for phrase in phrases:
        t0 = time.perf_counter()
        phonemes = engine.phonemise(phrase, keep_ezafe=True)
        out.append((phonemes, 1000 * (time.perf_counter() - t0)))
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--kv-dir", type=Path, default=Path("/probe/onnx"))
    args = parser.parse_args()
    candidate_enc = args.kv_dir / "g2p_encoder_kv.onnx"
    candidate_dec = args.kv_dir / "g2p_decoder_kv.onnx"
    for filename in (candidate_enc, candidate_dec):
        if not filename.is_file():
            raise SystemExit("FORZA_G2P_KV_ABORT missing=" + str(filename))
    print("FORZA_G2P_KV_SOURCE onnxruntime=" + ort.__version__, flush=True)

    # Run the same public phrases with baseline first and release it to
    # prevent overlapping two heavy G2P sessions in a 2-GiB container.
    baseline = OnnxG2P(MODEL)
    t0 = time.perf_counter()
    old = timed_phonemes(baseline, PHRASES)
    baseline_ms = round(1000 * (time.perf_counter() - t0))
    del baseline
    gc.collect()
    print("FORZA_G2P_BASELINE total_ms=%d cases=%d" %
          (baseline_ms, len(PHRASES)), flush=True)

    enc = session(candidate_enc)
    dec = session(candidate_dec)
    print("FORZA_G2P_KV_ABI " + json.dumps(
        {"encoder": manifest(enc), "decoder": manifest(dec)},
        separators=(",", ":"), ensure_ascii=True), flush=True)
    del enc, dec
    gc.collect()
    try:
        candidate = CachedG2P(args.kv_dir)
        t0 = time.perf_counter()
        new = timed_phonemes(candidate, PHRASES)
        candidate_ms = round(1000 * (time.perf_counter() - t0))
        matches = sum(a == b for (a, _), (b, _) in zip(old, new))
        print("FORZA_G2P_KV_RESULT baseline_ms=%d kv_ms=%d speedup=%.3fx exact_matches=%d cases=%d" %
              (baseline_ms, candidate_ms,
               baseline_ms / candidate_ms if candidate_ms > 0 else 0,
               matches, len(PHRASES)), flush=True)
        # Do not emit phoneme outputs; just fixed public case number.
        for index, ((a, ta), (b, tb)) in enumerate(zip(old, new), start=1):
            print("FORZA_G2P_KV_CASE idx=%d exact=%d baseline_ms=%d kv_ms=%d" %
                  (index, int(a == b), ta, tb), flush=True)
        if matches != len(PHRASES):
            raise SystemExit("FORZA_G2P_KV_REJECT phoneme_differences; production_unchanged=1")
        if candidate_ms >= baseline_ms:
            raise SystemExit("FORZA_G2P_KV_REJECT no_speedup; production_unchanged=1")
        print("FORZA_G2P_KV_PROBE_PASS possible_candidate_only=1 deployment=0", flush=True)
    except IncompatibleKV as exc:
        raise SystemExit("FORZA_G2P_KV_INCOMPATIBLE " + str(exc) +
                         " production_unchanged=1")


if __name__ == "__main__":
    main()
